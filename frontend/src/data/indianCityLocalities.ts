export function getLocalitiesForCity(city: string): string[] {
  return CITY_LOCALITIES[city] ?? [];
}

export function filterCityLocalities(city: string, query: string): string[] {
  const q = query.trim().toLowerCase();
  const localities = getLocalitiesForCity(city);
  if (!q) return localities;
  return localities.filter((locality) => locality.toLowerCase().includes(q));
}
